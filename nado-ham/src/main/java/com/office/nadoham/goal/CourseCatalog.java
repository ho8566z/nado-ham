    public static List<Course> all() {
        return COURSES;
    }

    public static Optional<Course> find(String code) {
        return COURSES.stream().filter(course -> course.code().equals(code)).findFirst();
    }

    private static Course.Session session(String title, String guide) {
        return new Course.Session(title, guide);
    }

    private static Course.Stage stage(String name, String goal, Course.Session first, Course.Session second, Course.Session third) {
        return new Course.Stage(name, goal, List.of(first, second, third));
    }

    // 직접 쓴 주차별 활동에 월 단계 이름·목표만 붙여 네 단계를 만든다
    private static List<Course.Stage> fromWeeks(List<List<Course.Session>> weeks, List<String> names, List<String> goals) {
        List<Course.Stage> stages = new ArrayList<>();
        for (int i = 0; i < weeks.size(); i++) {
            stages.add(new Course.Stage(names.get(i), goals.get(i), weeks.get(i)));
        }

        return stages;
    }

